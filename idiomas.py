def traducir(clave, idioma="es", **variables):
    """Devuelve un texto localizado; permite insertar porcentajes y fechas."""
    textos = TEXTOS.get(idioma, TEXTOS["es"])
    plantilla = textos.get(clave, TEXTOS["es"].get(clave, clave))
    return plantilla.format(**variables) if variables else plantilla


def validar_traducciones():
    """Retorna las claves que falten en inglés o en español."""
    return {
        "faltantes_en": sorted(set(TEXTOS["es"]) - set(TEXTOS["en"])),
        "faltantes_es": sorted(set(TEXTOS["en"]) - set(TEXTOS["es"])),
    }
